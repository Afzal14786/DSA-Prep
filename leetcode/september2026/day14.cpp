#include <bits/stdc++.h>
using namespace std;

// Question Link : https://leetcode.com/problems/rectangle-overlap/description/?envType=daily-question&envId=2026-09-14

class Solution {
public:
    bool isRectangleOverlap(vector<int>& rec1, vector<int>& rec2) {
        return rec1[0] < rec2[2] && rec2[0] < rec1[2] && rec1[1] < rec2[3] && rec2[1] < rec1[3];
    }
};